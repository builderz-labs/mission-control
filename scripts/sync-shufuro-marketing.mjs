#!/usr/bin/env node

import { readFile } from 'node:fs/promises'
import { loadAiOpsConfig, loadAutoGeneratedApiKey, projectBySlug } from './ai-ops-config.mjs'

const BASE_URL = process.env.AI_OPS_URL || 'http://127.0.0.1:3000'
let API_KEY = process.env.AI_OPS_API_KEY || process.env.MC_API_KEY || ''

async function request(path, init = {}) {
  const headers = {
    'Content-Type': 'application/json',
    ...(API_KEY ? { Authorization: `Bearer ${API_KEY}` } : {}),
    ...(init.headers || {}),
  }
  const response = await fetch(`${BASE_URL}${path}`, { ...init, headers })
  const text = await response.text()
  let body = {}
  try { body = text ? JSON.parse(text) : {} } catch {}
  if (!response.ok) throw new Error(`${init.method || 'GET'} ${path} -> ${response.status}: ${text.slice(0, 300)}`)
  return body
}

function parseQueue(markdown) {
  const rows = []
  for (const raw of markdown.split(/\r?\n/)) {
    const line = raw.trim()
    if (!/^\|\s*\d{3}\s*\|/.test(line)) continue
    const cells = line.split('|').slice(1, -1).map((cell) => cell.trim())
    if (cells.length < 9) continue
    const [order, type, series, episode, title, layer, timing, format, status] = cells
    rows.push({ order, type, series, episode, title, layer, timing, format, status: status.toUpperCase() })
  }
  return rows
}

function mapTaskState(row) {
  if (row.status === 'REVIEW') return {
    status: 'review',
    approvalType: 'content',
    humanApproval: null,
    nextAction: 'Founder review: approve, request changes, or hold',
  }
  if (row.status === 'READY') return {
    status: 'in_progress',
    approvalType: null,
    humanApproval: 'approved',
    nextAction: 'Render the selected format and run QA',
  }
  if (row.status === 'RENDERED') return {
    status: 'in_progress',
    approvalType: null,
    humanApproval: 'approved',
    nextAction: 'Publish the rendered asset and verify the final URL',
  }
  return null
}

function chooseActiveRows(rows) {
  const currentExecution = rows.find((row) => row.status === 'READY' || row.status === 'RENDERED')
  const includeLegacyReview = process.env.AI_OPS_LEGACY_SHUFURO_APPROVALS === '1'
  const nextReview = includeLegacyReview ? rows.find((row) => row.status === 'REVIEW') : null
  const chosen = []
  for (const row of [currentExecution, nextReview]) {
    if (row && !chosen.some((item) => item.episode === row.episode)) chosen.push(row)
  }
  return chosen
}

async function upsertTask(project, queuePath, row, existingTasks) {
  const mapped = mapTaskState(row)
  if (!mapped) return null

  const existing = existingTasks.find((task) => {
    const metadata = task?.metadata && typeof task.metadata === 'object' ? task.metadata : {}
    return metadata.source_ref === row.episode && metadata.workflow === 'shufuro.content_publish'
  })

  const existingMeta = existing?.metadata && typeof existing.metadata === 'object' && !Array.isArray(existing.metadata)
    ? existing.metadata
    : {}
  const pendingDecision = row.status === 'REVIEW' && ['approved', 'changes_requested', 'held'].includes(existingMeta.human_approval)
    ? existingMeta.human_approval
    : null

  const metadata = {
    ...existingMeta,
    domain: 'marketing',
    project_slug: 'shufuro',
    workflow: 'shufuro.content_publish',
    source_ref: row.episode,
    source_order: row.order,
    source_status: row.status,
    source_queue_path: queuePath,
    content_type: row.type,
    series: row.series,
    layer: row.layer,
    timing: row.timing,
    selected_format: row.format,
    next_action: mapped.nextAction,
    approval_type: mapped.approvalType || null,
    ...(mapped.humanApproval ? { human_approval: mapped.humanApproval } : {}),
    ...(pendingDecision ? { human_approval: pendingDecision } : {}),
  }

  const payload = {
    title: `Shufuro ${row.episode} — ${row.title}`,
    description: `Content OS order ${row.order}. Source status: ${row.status}. Format: ${row.format}.`,
    status: pendingDecision && existing ? existing.status : mapped.status,
    priority: 'high',
    project_id: project.id,
    tags: ['marketing', 'shufuro', 'content-os'],
    metadata,
  }

  if (existing) {
    const body = await request(`/api/tasks/${existing.id}`, { method: 'PUT', body: JSON.stringify(payload) })
    return { state: 'updated', taskId: body.task?.id || existing.id, sourceRef: row.episode, sourceStatus: row.status }
  }

  const body = await request('/api/tasks', { method: 'POST', body: JSON.stringify(payload) })
  return { state: 'created', taskId: body.task?.id || null, sourceRef: row.episode, sourceStatus: row.status }
}


async function retireLegacyReviewTasks(existingTasks, activeRows) {
  const activeEpisodes = new Set(activeRows.map((row) => row.episode))
  const retired = []
  for (const task of existingTasks) {
    const meta = task?.metadata && typeof task.metadata === 'object' && !Array.isArray(task.metadata)
      ? task.metadata
      : {}
    if (meta.workflow !== 'shufuro.content_publish') continue
    if (String(meta.source_status || '').toUpperCase() !== 'REVIEW') continue
    if (activeEpisodes.has(meta.source_ref)) continue

    const metadata = {
      ...meta,
      approval_type: null,
      human_required: null,
      migrated_to_factory: true,
      migrated_factory_instance: 'marketing:shufuro',
      next_action: 'Approval migrated to Marketing Factory.',
    }
    delete metadata.human_approval

    await request(`/api/tasks/${task.id}`, {
      method: 'PUT',
      body: JSON.stringify({ status: 'backlog', metadata }),
    })
    retired.push({ taskId: task.id, sourceRef: meta.source_ref })
  }
  return retired
}

async function main() {
  const config = await loadAiOpsConfig()
  if (!API_KEY) API_KEY = await loadAutoGeneratedApiKey(config.path)
  if (!API_KEY) throw new Error('No AI Ops API key found. Start AI Ops Hub once first.')

  const shufuro = projectBySlug(config, 'shufuro')
  const queuePath = shufuro?.paths?.marketingQueue
  if (!shufuro || !queuePath) throw new Error('Shufuro marketingQueue is not configured.')

  const rows = parseQueue(await readFile(queuePath, 'utf8'))
  const activeRows = chooseActiveRows(rows)
  if (activeRows.length === 0) {
    console.log(JSON.stringify({ state: 'idle', message: 'No READY, RENDERED, or REVIEW Shufuro content item.' }))
    return
  }

  const projectsBody = await request('/api/projects')
  const project = (projectsBody.projects || []).find((row) => row.slug === 'shufuro')
  if (!project) throw new Error('Shufuro project does not exist in AI Ops Hub. Run pnpm aiops:bootstrap first.')

  const tasksBody = await request(`/api/tasks?project_id=${project.id}&limit=200`)
  const existingTasks = tasksBody.tasks || []

  const results = []
  for (const row of activeRows) {
    const result = await upsertTask(project, queuePath, row, existingTasks)
    if (result) results.push(result)
  }
  const retired = await retireLegacyReviewTasks(existingTasks, activeRows)
  console.log(JSON.stringify({ state: 'synced', items: results, retired }))
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
