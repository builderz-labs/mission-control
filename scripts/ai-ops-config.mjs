import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'

export function resolveConfigPath() {
  return resolve(process.env.AI_OPS_CONFIG || '.data/ai-ops-config.json')
}

export async function loadAiOpsConfig() {
  const path = resolveConfigPath()
  try {
    const text = await readFile(path, 'utf8')
    const parsed = JSON.parse(text)
    return {
      path,
      version: Number(parsed?.version || 1),
      projects: Array.isArray(parsed?.projects) ? parsed.projects : [],
      skillRoots: Array.isArray(parsed?.skillRoots) ? parsed.skillRoots : [],
    }
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      return { path, version: 1, projects: [], skillRoots: [] }
    }
    throw error
  }
}

export function projectBySlug(config, slug) {
  return config.projects.find((project) => project?.slug === slug) || null
}

export async function loadAutoGeneratedApiKey(configPath = resolveConfigPath()) {
  const dataDir = resolve(configPath, '..')
  const generatedPath = resolve(dataDir, '.auto-generated')
  try {
    const text = await readFile(generatedPath, 'utf8')
    for (const line of text.split(/\r?\n/)) {
      const trimmed = line.trim()
      if (!trimmed || trimmed.startsWith('#')) continue
      const idx = trimmed.indexOf('=')
      if (idx < 0) continue
      const key = trimmed.slice(0, idx).trim()
      const value = trimmed.slice(idx + 1).trim()
      if (key === 'API_KEY' && value) return value
    }
  } catch (error) {
    if (!error || error.code !== 'ENOENT') throw error
  }
  return ''
}
