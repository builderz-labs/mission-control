#!/usr/bin/env node

import { spawn } from 'node:child_process'
import { loadAiOpsConfig, loadAutoGeneratedApiKey, projectBySlug } from './ai-ops-config.mjs'
import { promoteShufuroReview } from './shufuro-content-bridge.mjs'

const BASE_URL = process.env.AI_OPS_URL || 'http://127.0.0.1:3000'
let API_KEY = process.env.AI_OPS_API_KEY || process.env.MC_API_KEY || ''
const POLL_MS = Number(process.env.AI_OPS_POLL_MS || 5000)
const once = process.argv.includes('--once')
const seen = new Map()
let config = { projects: [], skillRoots: [] }
let lastSourceSyncAt = 0
const SOURCE_SYNC_MS = Number(process.env.AI_OPS_SOURCE_SYNC_MS || 60000)

function taskMeta(task) {
  return task && task.metadata && typeof task.metadata === 'object' && !Array.isArray(task.metadata)
    ? task.metadata
    : {}
}

async function request(path, init = {}) {
  const headers = {
    'Content-Type': 'application/json',
    ...(API_KEY ? { Authorization: `Bearer ${API_KEY}` } : {}),
    ...(init.headers || {}),
  }
  const response = await fetch(`${BASE_URL}${path}`, { ...init, headers })
  if (!response.ok) {
    const body = await response.text().catch(() => '')
    throw new Error(`${init.method || 'GET'} ${path} -> ${response.status}: ${body.slice(0, 300)}`)
  }
  return response.json()
}

async function listApprovedTasks() {
  const statuses = ['assigned', 'in_progress']
  const rows = []
  for (const status of statuses) {
    const body = await request(`/api/tasks?status=${status}&limit=200`)
    for (const task of body.tasks || []) {
      const meta = taskMeta(task)
      if (meta.human_approval === 'approved' && typeof meta.workflow === 'string') {
        rows.push(task)
      }
    }
  }
  return rows
}

const handlers = {
  async 'shufuro.content_publish'(task) {
    const meta = taskMeta(task)
    const project = projectBySlug(config, 'shufuro')
    const sourceStatus = String(meta.source_status || '').toUpperCase()

    if (sourceStatus === 'REVIEW') {
      const promotion = await promoteShufuroReview(task)
      const metadata = {
        ...meta,
        source_status: 'READY',
        approval_type: null,
        next_action: 'Render the selected format and run QA',
        runner_transition: 'review_to_ready',
        runner_transition_at: Math.floor(Date.now() / 1000),
      }
      await request(`/api/tasks/${task.id}`, {
        method: 'PUT',
        body: JSON.stringify({ status: 'in_progress', metadata }),
      })
      return {
        taskId: task.id,
        workflow: meta.workflow,
        project: project?.slug || 'shufuro',
        state: 'promoted_ready',
        message: `${promotion.episode} promoted from REVIEW to READY in Obsidian and AI Ops Hub.`,
      }
    }

    if (sourceStatus === 'READY') {
      return {
        taskId: task.id,
        workflow: meta.workflow,
        project: project?.slug || 'shufuro',
        state: 'waiting_renderer',
        message: 'READY is approved. Renderer/QA adapter is the next implementation gate.',
      }
    }

    if (sourceStatus === 'RENDERED') {
      return {
        taskId: task.id,
        workflow: meta.workflow,
        project: project?.slug || 'shufuro',
        state: 'waiting_publisher',
        message: 'Rendered asset is ready for the publishing operator.',
      }
    }

    return {
      taskId: task.id,
      workflow: meta.workflow,
      project: project?.slug || 'shufuro',
      state: 'waiting_source_state',
      message: `Unsupported Shufuro Content OS state: ${sourceStatus || 'unknown'}`,
    }
  },

  async 'productbaton.content_publish'(task) {
    const project = projectBySlug(config, 'productbaton')
    return {
      taskId: task.id,
      workflow: taskMeta(task).workflow,
      project: project?.slug || 'productbaton',
      state: 'waiting_adapter',
      message: 'ProductBaton marketing adapter is reserved for the next workflow phase.',
    }
  },

  async 'development.build_test_fix'(task) {
    return {
      taskId: task.id,
      workflow: taskMeta(task).workflow,
      state: 'waiting_adapter',
      message: 'Development loop adapter is reserved for the development workflow phase.',
    }
  },
}

async function dispatch(task) {
  const meta = taskMeta(task)
  const workflow = meta.workflow
  const handler = handlers[workflow]

  if (!handler) {
    return {
      taskId: task.id,
      workflow,
      state: 'unregistered',
      message: 'No allowlisted runner adapter is registered for this workflow.',
    }
  }

  return handler(task)
}

async function syncSourceQueuesIfDue() {
  const now = Date.now()
  if (now - lastSourceSyncAt < SOURCE_SYNC_MS) return
  lastSourceSyncAt = now

  await new Promise((resolve) => {
    const child = spawn(process.execPath, ['scripts/sync-shufuro-marketing.mjs'], {
      cwd: process.cwd(),
      env: process.env,
      stdio: ['ignore', 'pipe', 'pipe'],
    })
    let stdout = ''
    let stderr = ''
    child.stdout.on('data', (chunk) => { stdout += chunk.toString() })
    child.stderr.on('data', (chunk) => { stderr += chunk.toString() })
    child.on('error', (error) => {
      console.error(`[${new Date().toISOString()}] source sync error:`, error.message)
      resolve()
    })
    child.on('close', (code) => {
      if (code === 0) {
        const line = stdout.trim().split(/\r?\n/).filter(Boolean).at(-1)
        if (line) console.log(JSON.stringify({ ts: new Date().toISOString(), state: 'source_sync', result: line }))
      } else {
        console.error(`[${new Date().toISOString()}] source sync exited ${code}:`, stderr.trim() || stdout.trim())
      }
      resolve()
    })
  })
}

async function tick() {
  await syncSourceQueuesIfDue()
  const tasks = await listApprovedTasks()
  for (const task of tasks) {
    const signature = `${task.id}:${task.updated_at}:${JSON.stringify(task.metadata || {})}`
    if (seen.get(task.id) === signature) continue
    seen.set(task.id, signature)

    const result = await dispatch(task)
    const ts = new Date().toISOString()
    console.log(JSON.stringify({ ts, ...result }))
  }
  return tasks.length
}

async function main() {
  config = await loadAiOpsConfig()
  if (!API_KEY) API_KEY = await loadAutoGeneratedApiKey(config.path)

  if (!API_KEY) {
    console.error('No AI Ops API key was found. Start the hub once so it can generate .data/.auto-generated credentials.')
    process.exit(2)
  }

  console.log(`AI Ops Runner connected to ${BASE_URL}. Poll interval: ${POLL_MS}ms`)
  do {
    try {
      await tick()
    } catch (error) {
      console.error(`[${new Date().toISOString()}] runner error:`, error instanceof Error ? error.message : error)
    }

    if (once) break
    await new Promise((resolve) => setTimeout(resolve, POLL_MS))
  } while (true)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
