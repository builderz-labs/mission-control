#!/usr/bin/env node

import { loadAiOpsConfig, loadAutoGeneratedApiKey } from './ai-ops-config.mjs'

const BASE_URL = process.env.AI_OPS_URL || 'http://127.0.0.1:3000'
let API_KEY = process.env.AI_OPS_API_KEY || process.env.MC_API_KEY || ''

async function request(path, init = {}) {
  const headers = {
    'Content-Type': 'application/json',
    ...(API_KEY ? { Authorization: `Bearer ${API_KEY}` } : {}),
    ...(init.headers || {}),
  }
  const response = await fetch(`${BASE_URL}${path}`, { ...init, headers })
  const text = await response.text()
  let body = {}
  try { body = text ? JSON.parse(text) : {} } catch {}
  if (!response.ok) {
    throw new Error(`${init.method || 'GET'} ${path} -> ${response.status}: ${text.slice(0, 300)}`)
  }
  return body
}

async function ensureProject(project) {
  const current = await request('/api/projects')
  const existing = (current.projects || []).find((row) => row.slug === project.slug)

  if (existing) {
    return { action: 'exists', project: existing }
  }

  const body = await request('/api/projects', {
    method: 'POST',
    body: JSON.stringify({
      name: project.name,
      slug: project.slug,
      ticket_prefix: project.ticketPrefix,
      description: project.description,
      github_repo: project.githubRepo,
      color: project.color,
    }),
  })

  return { action: 'created', project: body.project }
}

async function main() {
  const config = await loadAiOpsConfig()
  if (!API_KEY) API_KEY = await loadAutoGeneratedApiKey(config.path)
  if (!API_KEY) {
    console.error('No AI Ops API key was found. Start the hub once so it can generate local credentials.')
    process.exit(2)
  }
  if (config.projects.length === 0) {
    console.log(`No projects configured in ${config.path}`)
    return
  }

  for (const project of config.projects) {
    const result = await ensureProject(project)
    console.log(JSON.stringify({
      project: project.slug,
      action: result.action,
      id: result.project?.id ?? null,
      name: result.project?.name ?? project.name,
    }))
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
